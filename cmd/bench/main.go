// The locked NFR bounds (.agents/specs/memory-store.md, "Non-functional
// requirements"): open < 50 ms and search p95 < 50 ms at 10^4 memories. The
// spec bounds nothing else here: the 10x p95 delta and the size ratio are
// stated there as measured observations, so this harness prints them without a
// verdict.
const (
	nfrOpenMs   = 50.0 // open < 50 ms
	nfrSearchMs = 50.0 // search p95 < 50 ms at 10^4 memories
)

// The corpus is synthetic and fixed: the same bytes at every N, so the 1e3 run
// is exactly the first 1e3 memories of the 1e4 run. It is generated by a
// linear congruential generator whose constants are written out here, not by
// math/rand, so it is reproducible without depending on the standard library's
// sequence.
const (
	lcgA       = uint64(6364136223846793005)
	lcgC       = uint64(1442695040888963407)
	corpusSeed = uint64(0x9E3779B97F4A7C15)
	querySeed  = uint64(0xD1B54A32D192ED03)
	docWords   = 12
)

type lcg uint64

func (l *lcg) next() uint64 {
	*l = lcg(uint64(*l)*lcgA + lcgC)
	return uint64(*l)
}

// pick takes the high 32 bits of the state, so the low-order regularity of the
// modulus does not show up in the choice.
func (l *lcg) pick(v []string) string { return v[int(l.next()>>32)%len(v)] }

// baseWords are 64 fixed words; the vocabulary is these crossed with the
// suffixes "", "a", "b", "c" — 256 distinct tokens.
var baseWords = []string{
	"spec", "lock", "worker", "store", "search", "memory", "node", "card",
	"commit", "report", "probe", "bench", "index", "target", "bound", "bytes",
	"file", "query", "recall", "fuse", "token", "scope", "kind", "status",
	"event", "plan", "gate", "check", "build", "test", "error", "trace",
	"branch", "merge", "review", "signal", "metric", "cache", "stream", "buffer",
	"ledger", "origin", "parent", "child", "anchor", "vector", "lexical", "graph",
	"walk", "fusion", "delta", "ratio", "floor", "ceiling", "window", "shard",
	"tier", "claim", "draft", "policy", "budget", "canvas", "annotate", "herdr",
}

var vocab = func() []string {
	out := make([]string, 0, len(baseWords)*4)
	for _, suffix := range []string{"", "a", "b", "c"} {
		for _, w := range baseWords {
			out = append(out, w+suffix)
		}
	}
	return out
}()

// corpus returns n memories, each 12 words drawn from vocab.
func corpus(n int) []memstore.Memory {
	r := lcg(corpusSeed)
	out := make([]memstore.Memory, n)
	for i := range out {
		words := make([]string, docWords)
		for j := range words {
			words[j] = r.pick(vocab)
		}
		out[i] = memstore.Memory{Kind: "probe", Scope: "bench", Text: strings.Join(words, " ")}
	}
	return out
}

// querySet returns q queries, each two tokens drawn from vocab. The same set
// runs at every N.
func querySet(q int) []string {
	r := lcg(querySeed)
	out := make([]string, q)
	for i := range out {
		out[i] = r.pick(vocab) + " " + r.pick(vocab)
	}
	return out
}

type config struct {
	sizes    []int
	queries  int
	k        int
	passes   int
	openReps int
	work     string
	part     string

	// Part C — the scope-listing read.
	memsrc string
	scopeK int
	runs   int
	warmup int
	scopes int
}

func main() {
	var (
		nFlag    = flag.String("n", "1000,10000", "comma-separated corpus sizes")
		queries  = flag.Int("queries", 100, "size of the fixed query set")
		k        = flag.Int("k", 10, "search result limit")
		passes   = flag.Int("passes", 3, "timed passes over the query set")
		openReps = flag.Int("openreps", 30, "open repetitions per phase")
		work     = flag.String("work", "", "working directory (default: a fresh temp dir)")
		part     = flag.String("part", "all", "a, c, or all")
		memsrc   = flag.String("memsrc", "~/.memstore/memory.db", "memstore file for part C (copied, never opened in place)")
		scopeK   = flag.Int("scopek", 1<<20, "k a scope listing asks for in part C (fs's recentLimit)")
		runs     = flag.Int("runs", 30, "timed runs per scope in part C")
		warmup   = flag.Int("warmup", 5, "untimed warm-up calls per scope in part C")
		scopes   = flag.Int("scopes", 5, "scopes measured in part C, by row count")
	)
	flag.Parse()

	cfg := config{queries: *queries, k: *k, passes: *passes, openReps: *openReps, part: *part,
		memsrc: expandHome(*memsrc), scopeK: *scopeK, runs: *runs, warmup: *warmup, scopes: *scopes}
	for _, s := range strings.Split(*nFlag, ",") {
		s = strings.TrimSpace(s)
		if s == "" {
			continue
		}
		var v int
		if _, err := fmt.Sscanf(s, "%d", &v); err != nil {
			fatal("bad -n %q: %v", s, err)
		}
		cfg.sizes = append(cfg.sizes, v)
	}
	cfg.work = *work
	if cfg.work == "" {
		d, err := os.MkdirTemp("", "memstore-bench-")
		if err != nil {
			fatal("mktemp: %v", err)
		}
		cfg.work = d
	}
	if err := os.MkdirAll(cfg.work, 0o700); err != nil {
		fatal("work dir: %v", err)
	}
	sort.Ints(cfg.sizes)

	if cfg.part == "a" || cfg.part == "all" {
		if err := partA(cfg); err != nil {
			fatal("part A: %v", err)
		}
	}
	if cfg.part == "c" || cfg.part == "all" {
		if err := partC(cfg); err != nil {
			fatal("part C: %v", err)
		}
	}
	if cfg.part == "d" || cfg.part == "all" {
		if err := partD(cfg); err != nil {
			fatal("part D: %v", err)
		}
	}
}

func fatal(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "bench: "+format+"\n", args...)
	os.Exit(1)
}

func expandHome(p string) string {
	if strings.HasPrefix(p, "~/") {
		home, err := os.UserHomeDir()
		if err == nil {
			return filepath.Join(home, p[2:])
		}
	}
	return p
}

func ms(since time.Time) float64 { return float64(time.Since(since).Nanoseconds()) / 1e6 }

// pctl is the nearest-rank percentile, p in [0,100].
func pctl(xs []float64, p float64) float64 {
	if len(xs) == 0 {
		return math.NaN()
	}
	s := append([]float64(nil), xs...)
	sort.Float64s(s)
	i := int(math.Ceil(p/100*float64(len(s)))) - 1
	if i < 0 {
		i = 0
	}
	if i >= len(s) {
		i = len(s) - 1
	}
	return s[i]
}

func meanInts(xs []int) float64 {
	if len(xs) == 0 {
		return math.NaN()
	}
	t := 0
	for _, x := range xs {
		t += x
	}
	return float64(t) / float64(len(xs))
}

type result struct {
	n         int
	freshOpen []float64
	rowOpen   []float64
	putMs     []float64
	putWall   time.Duration
	searchMs  []float64
	hits      []int
	dbBytes   int64
	textBytes int64
	walBytes  int64
	dbPath    string
}

func partA(cfg config) error {
	mems := corpus(cfg.sizes[len(cfg.sizes)-1])
	qs := querySet(cfg.queries)

	fmt.Printf("=== Part A: NFR benchmark ===\n")
	fmt.Printf("corpus: each memory is %d words drawn from a fixed %d-token vocabulary (%d base words x suffixes \"\",a,b,c), generated by an LCG (a=%d c=%d seed=%#x). The corpus for N is the first N memories of one sequence, so the N=1000 run is the head of the N=10000 run.\n", docWords, len(vocab), len(baseWords), lcgA, lcgC, corpusSeed)
	fmt.Printf("query set: %d queries, each two tokens drawn from the same vocabulary (seed=%#x); k=%d; %d timed passes after one warm-up pass; identical at every N. (state-the-set: %d queries, 2-token OR, drawn from the 256-token synthetic vocabulary; a hit needs either token and bm25 ranks)\n", cfg.queries, querySeed, cfg.k, cfg.passes, cfg.queries)
	fmt.Printf("bounds under test: open < %.0f ms | search p95 < %.0f ms at N=10000\n", nfrOpenMs, nfrSearchMs)
	fmt.Printf("observations (no bound): search p95 10x delta; db bytes over text bytes\n\n")

	var got []result
	for _, n := range cfg.sizes {
		r, err := runOne(cfg, mems[:n], qs)
		if err != nil {
			return err
		}
		got = append(got, r)
		printResult(r, qs, cfg.k)
	}
	printNFRSection(got)
	return nil
}

func runOne(cfg config, mems []memstore.Memory, qs []string) (result, error) {
	var r result
	n := len(mems)
	r.n = n
	dbPath := filepath.Join(cfg.work, fmt.Sprintf("n%d", n), "memory.db")
	r.dbPath = dbPath
	if err := os.MkdirAll(filepath.Dir(dbPath), 0o700); err != nil {
		return r, err
	}

	// Open, fresh: a path that does not exist. Open creates the schema, so
	// this is the first-open cost, not a plain file open.
	for i := 0; i < cfg.openReps; i++ {
		for _, p := range []string{dbPath, dbPath + "-wal", dbPath + "-shm"} {
			os.Remove(p)
		}
		t0 := time.Now()
		s, err := memstore.Open(dbPath)
		if err != nil {
			return r, fmt.Errorf("fresh open %d/%d: %w", i, cfg.openReps, err)
		}
		r.freshOpen = append(r.freshOpen, ms(t0))
		if err := s.Close(); err != nil {
			return r, err
		}
	}

	// Put: one store, one Put at a time, each Put its own transaction.
	s, err := memstore.Open(dbPath)
	if err != nil {
		return r, err
	}
	start := time.Now()
	for i := range mems {
		t0 := time.Now()
		if _, err := s.Put(&mems[i]); err != nil {
			s.Close()
			return r, fmt.Errorf("put %d: %w", i, err)
		}
		r.putMs = append(r.putMs, ms(t0))
	}
	r.putWall = time.Since(start)
	if err := s.Close(); err != nil {
		return r, err
	}

	// Size, measured at rest: after Close the WAL sidecars are checkpointed
	// away, so one file holds everything.
	fi, err := os.Stat(dbPath)
	if err != nil {
		return r, err
	}
	r.dbBytes = fi.Size()
	if wfi, err := os.Stat(dbPath + "-wal"); err == nil {
		r.walBytes = wfi.Size()
	}
	for i := range mems {
		r.textBytes += int64(len(mems[i].Text))
	}

	// Open, with rows present.
	for i := 0; i < cfg.openReps; i++ {
		t0 := time.Now()
		s, err := memstore.Open(dbPath)
		if err != nil {
			return r, fmt.Errorf("row open %d/%d: %w", i, cfg.openReps, err)
		}
		r.rowOpen = append(r.rowOpen, ms(t0))
		if err := s.Close(); err != nil {
			return r, err
		}
	}

	// Search: one un-timed warm-up pass over the set, then cfg.passes timed.
	s, err = memstore.Open(dbPath)
	if err != nil {
		return r, err
	}
	for _, q := range qs {
		if _, err := s.Search(q, cfg.k); err != nil {
			s.Close()
			return r, fmt.Errorf("warm-up search %q: %w", q, err)
		}
	}
	for pass := 0; pass < cfg.passes; pass++ {
		for _, q := range qs {
			t0 := time.Now()
			h, err := s.Search(q, cfg.k)
			if err != nil {
				s.Close()
				return r, fmt.Errorf("search %q: %w", q, err)
			}
			r.searchMs = append(r.searchMs, ms(t0))
			if pass == 0 {
				r.hits = append(r.hits, len(h))
			}
		}
	}
	if err := s.Close(); err != nil {
		return r, err
	}
	return r, nil
}

func printResult(r result, qs []string, k int) {
	ratio := float64(r.dbBytes) / float64(r.textBytes)
	fmt.Printf("--- N=%d  (%s) ---\n", r.n, r.dbPath)
	fmt.Printf("open fresh        : %d reps, p50 %.3f ms, p95 %.3f ms\n", len(r.freshOpen), pctl(r.freshOpen, 50), pctl(r.freshOpen, 95))
	fmt.Printf("open with %5d rows: %d reps, p50 %.3f ms, p95 %.3f ms\n", r.n, len(r.rowOpen), pctl(r.rowOpen, 50), pctl(r.rowOpen, 95))
	fmt.Printf("put               : %d puts in %.3f s -> %.0f puts/s; per-put p50 %.3f ms, p95 %.3f ms\n", r.n, r.putWall.Seconds(), float64(r.n)/r.putWall.Seconds(), pctl(r.putMs, 50), pctl(r.putMs, 95))
	fmt.Printf("search            : %d samples over %d queries (warm-up discarded), p50 %.3f ms, p95 %.3f ms; mean hits/query %.2f of k=%d\n", len(r.searchMs), len(qs), pctl(r.searchMs, 50), pctl(r.searchMs, 95), meanInts(r.hits), k)
	fmt.Printf("size              : db %d B, wal-at-rest %d B, text %d B -> ratio %.3f\n", r.dbBytes, r.walBytes, r.textBytes, ratio)
	fmt.Println()
}

func printNFRSection(rs []result) {
	fmt.Printf("=== NFR table (bounds: open < %.0f ms; search p95 < %.0f ms at N=10000) ===\n", nfrOpenMs, nfrSearchMs)
	for _, r := range rs {
		openP95 := math.Max(pctl(r.freshOpen, 95), pctl(r.rowOpen, 95))
		verdict := "PASS"
		if openP95 >= nfrOpenMs {
			verdict = "FAIL"
		}
		fmt.Printf("N=%-6d open p95 (worst of fresh/rows): %8.3f ms   bound %5.0f ms   %s\n", r.n, openP95, nfrOpenMs, verdict)
	}
	if len(rs) > 0 {
		last := rs[len(rs)-1]
		v := "PASS"
		if pctl(last.searchMs, 95) >= nfrSearchMs {
			v = "FAIL"
		}
		fmt.Printf("N=%-6d search p95                    : %8.3f ms   bound %5.0f ms   %s\n", last.n, pctl(last.searchMs, 95), nfrSearchMs, v)
	}
	if len(rs) == 2 {
		d := pctl(rs[1].searchMs, 95) / pctl(rs[0].searchMs, 95)
		fmt.Printf("10x delta (search p95 %d/%d): %.3fx   (observation; the spec bounds no 10x ratio)\n", rs[1].n, rs[0].n, d)
	}
	for _, r := range rs {
		ratio := float64(r.dbBytes) / float64(r.textBytes)
		fmt.Printf("N=%-6d size ratio (db/text)          : %8.3f      (observation; the spec bounds no size ratio)\n", r.n, ratio)
	}
	fmt.Println()
}

// benchMemoryCols is the column list Recent reads, in scan order. Part C asks
// the plan for the query Recent issues, so the projection must match.
const benchMemoryCols = `memory.id, memory.ts, memory.kind, memory.scope, memory.title,
	memory.text, memory.extra, memory.importance, memory.tier, memory.status,
	memory.deleted_at, memory.parent, memory.supersedes, memory.found_by, memory.hash,
	memory.origin, memory.origin_id, memory.ref, memory.fs_node`

// queryPlan renders one EXPLAIN QUERY PLAN for a query as a single line, so the
// plan SQLite chose can be pasted as evidence.
func queryPlan(db *sql.DB, query string, args ...any) (string, error) {
	rows, err := db.Query(`EXPLAIN QUERY PLAN `+query, args...)
	if err != nil {
		return "", err
	}
	defer rows.Close()
	var parts []string
	for rows.Next() {
		var id, parent, notused int
		var detail string
		if err := rows.Scan(&id, &parent, &notused, &detail); err != nil {
			return "", err
		}
		parts = append(parts, detail)
	}
	if err := rows.Err(); err != nil {
		return "", err
	}
	return strings.Join(parts, " | "), nil
}

// printSpread reports a timing sample with its spread: min, p50, p95 and max.
// The median alone is not evidence on a machine running other agents, so the
// tails are printed beside it.
func printSpread(label string, rows int, xs []float64) {
	fmt.Printf("%-46s rows %5d  min %8.3f  p50 %8.3f  p95 %8.3f  max %8.3f ms\n",
		label, rows, pctl(xs, 0), pctl(xs, 50), pctl(xs, 95), pctl(xs, 100))
}

// partC measures the scope-listing read — Store.Recent(scope, k) — on a copy of
// a real store, with the plan SQLite answers it with. This is the number this
// round turns on: the acceptance is the READ's cost, not the index's existence,
// and a speedup without its spread is not evidence. It copies the source (db
// plus sidecars) and never opens the original in place, the rule part B keeps.
//
// The before/after pair is not two code paths here: run this part against a
// store the previous revision wrote (schema_version 5) and again against the
// same store once Open has carried it to the current version, one protocol each.
// profileBoundMs is the personal-profile read's p95 bound (.agents/specs/
// personal-profile.md, Non-functional requirements): under 50 ms at 10^4 rows.
const profileBoundMs = 50.0

// partD times the digest read over a generated store at the largest size in
// the -n list. The corpus is the same synthetic one Part A uses; the digest's
// verdict is a bound, so it prints PASS or FAIL against profileBoundMs.
func partD(cfg config) error {
	if len(cfg.sizes) == 0 {
		return fmt.Errorf("no sizes")
	}
	n := cfg.sizes[len(cfg.sizes)-1]
	fmt.Printf("=== Part D: personal-profile digest read (Profile k=8) at N=%d ===\n", n)
	path := filepath.Join(cfg.work, "profile.db")
	s, err := memstore.Open(path)
	if err != nil {
		return err
	}
	defer s.Close()
	for i, m := range corpus(n) {
		// The digest reads titled factors. Part A's corpus has no title, so
		// every row would be excluded and the timing would measure the
		// empty-title fast path. Give each row a title drawn from a fixed
		// set of 50, and vary kind and scope, so the read does real work.
		m.Title = fmt.Sprintf("title %02d", i%50)
		m.Kind = []string{"error", "decision", "preference", "gate", "build", "event"}[i%6]
		m.Scope = []string{"fs:a", "fs:b", "personal", "agent"}[i%4]
		if _, err := s.Put(&m); err != nil {
			return fmt.Errorf("put: %w", err)
		}
	}
	for i := 0; i < cfg.warmup; i++ {
		if _, err := s.Profile(nil, 8); err != nil {
			return err
		}
	}
	ms := make([]float64, 0, cfg.runs)
	var d memstore.Digest
	for i := 0; i < cfg.runs; i++ {
		t := time.Now()
		d, err = s.Profile(nil, 8)
		if err != nil {
			return err
		}
		ms = append(ms, ms2(t))
	}
	sort.Float64s(ms)
	p95 := pctl(ms, 95)
	verdict := "PASS"
	if p95 >= profileBoundMs {
		verdict = "FAIL"
	}
	printSpread("Profile(k=8)", n, ms)
	fmt.Printf("digest: %d factors returned, %d omitted\n", len(d.Factors), d.Omitted)
	fmt.Printf("bound p95 < %.0f ms: %s (p95 %.3f ms)\n\n", profileBoundMs, verdict, p95)
	return nil
}

// ms2 is the elapsed time since t, in milliseconds.
func ms2(t time.Time) float64 { return float64(time.Since(t).Nanoseconds()) / 1e6 }

func partC(cfg config) error {
	fmt.Printf("=== Part C: scope-listing read cost (Recent) ===\n")
	srcStat, err := os.Stat(cfg.memsrc)
	if err != nil {
		return fmt.Errorf("memstore source %s: %w", cfg.memsrc, err)
	}
	copyPath := filepath.Join(cfg.work, "scope-copy.db")
	for _, suf := range []string{"", "-wal", "-shm"} {
		if _, serr := os.Stat(cfg.memsrc + suf); serr != nil {
			continue
		}
		if err := copyFile(copyPath+suf, cfg.memsrc+suf); err != nil {
			return err
		}
	}
	fmt.Printf("source     : %s (%d B) -- copied to %s; the original is never opened in place\n", cfg.memsrc, srcStat.Size(), copyPath)

	s, err := memstore.Open(copyPath)
	if err != nil {
		return err
	}
	defer s.Close()

	db, err := sql.Open("sqlite", copyPath)
	if err != nil {
		return err
	}
	defer db.Close()
	db.SetMaxOpenConns(1)

	var v, total, live int
	if err := db.QueryRow(`SELECT version FROM schema_version`).Scan(&v); err != nil {
		return err
	}
	if err := db.QueryRow(`SELECT count(*), coalesce(sum(deleted_at IS NULL), 0) FROM memory`).Scan(&total, &live); err != nil {
		return err
	}
	var idx string
	if err := db.QueryRow(`SELECT coalesce((SELECT sql FROM sqlite_master WHERE type = 'index' AND name = 'idx_memory_scope_recent'), '(absent)')`).Scan(&idx); err != nil {
		return err
	}
	fmt.Printf("store shape: schema_version %d, %d rows, %d live; scope index: %s\n", v, total, live, idx)
	fmt.Printf("protocol   : %d warm-up calls discarded, then %d timed calls per scope, one process and one connection; min/p50/p95/max ms; k=%d (fs's recentLimit)\n", cfg.warmup, cfg.runs, cfg.scopeK)

	// The scopes the store actually holds, biggest first. A scope listing is for
	// one of them, so these are the reads worth timing. The empty scope is
	// skipped: Recent("") is the whole store, not a scope listing, and its row
	// count would make the label lie.
	srows, err := db.Query(`SELECT scope, count(*) FROM memory WHERE deleted_at IS NULL AND scope <> '' GROUP BY scope ORDER BY count(*) DESC, scope LIMIT ?`, cfg.scopes)
	if err != nil {
		return err
	}
	type scopeCount struct {
		scope string
		n     int
	}
	var list []scopeCount
	for srows.Next() {
		var sc scopeCount
		if err := srows.Scan(&sc.scope, &sc.n); err != nil {
			srows.Close()
			return err
		}
		list = append(list, sc)
	}
	srows.Close()
	if err := srows.Err(); err != nil {
		return err
	}
	if len(list) == 0 {
		fmt.Println("plan       : (no live rows; nothing to list)")
		fmt.Println()
		return nil
	}

	plan, err := queryPlan(db, `SELECT `+benchMemoryCols+` FROM memory WHERE deleted_at IS NULL AND scope = ? ORDER BY ts DESC, id DESC LIMIT ?`, list[0].scope, cfg.scopeK)
	if err != nil {
		return err
	}
	fmt.Printf("plan       : Recent(%q, k): %s\n", list[0].scope, plan)

	for _, sc := range list {
		call := func() error {
			_, err := s.Recent(sc.scope, cfg.scopeK)
			return err
		}
		for i := 0; i < cfg.warmup; i++ {
			if err := call(); err != nil {
				return err
			}
		}
		xs := make([]float64, 0, cfg.runs)
		for i := 0; i < cfg.runs; i++ {
			t0 := time.Now()
			if err := call(); err != nil {
				return err
			}
			xs = append(xs, ms(t0))
		}
		printSpread(fmt.Sprintf("Recent(%q, %d)", sc.scope, cfg.scopeK), sc.n, xs)
	}
	fmt.Println()
	return nil
}

type kindCount struct {
	kind string
	n    int
}

func reportKinds(path string) ([]kindCount, int, error) {
	db, err := sql.Open("sqlite", path)
	if err != nil {
		return nil, 0, err
	}
	defer db.Close()
	rows, err := db.Query(`SELECT kind, count(*) FROM memory GROUP BY kind ORDER BY count(*) DESC, kind`)
	if err != nil {
		return nil, 0, err
	}
	defer rows.Close()
	var out []kindCount
	total := 0
	for rows.Next() {
		var k kindCount
		if err := rows.Scan(&k.kind, &k.n); err != nil {
			return nil, 0, err
		}
		out = append(out, k)
		total += k.n
	}
	return out, total, rows.Err()
}

func reportTextBytes(path string) (int64, error) {
	db, err := sql.Open("sqlite", path)
	if err != nil {
		return 0, err
	}
	defer db.Close()
	var n int64
	if err := db.QueryRow(`SELECT coalesce(sum(length(CAST(text AS BLOB))), 0) FROM memory`).Scan(&n); err != nil {
		return 0, err
	}
	return n, nil
}

func reportTs(path string) (oldest, newest string, err error) {
	db, err := sql.Open("sqlite", path)
	if err != nil {
		return "", "", err
	}
	defer db.Close()
	var lo, hi sql.NullInt64
	if err := db.QueryRow(`SELECT min(ts), max(ts) FROM memory`).Scan(&lo, &hi); err != nil {
		return "", "", err
	}
	if !lo.Valid || !hi.Valid {
		return "", "", nil
	}
	return time.Unix(0, lo.Int64).UTC().Format(time.RFC3339Nano), time.Unix(0, hi.Int64).UTC().Format(time.RFC3339Nano), nil
}

func copyFile(dst, src string) error {
	n, err := os.Open(src)
	if err != nil {
		return err
	}
	defer n.Close()
	out, err := os.Create(dst)
	if err != nil {
		return err
	}
	if _, err := io.Copy(out, n); err != nil {
		out.Close()
		os.Remove(dst)
		return err
	}
	return out.Close()
}
